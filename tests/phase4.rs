fn simple_agent(name: &str) -> Agent {
    Agent {
        name: name.to_string(),
        description: format!("{} agent", name),
        pipeline: Pipeline {
            name: format!("{}_pipeline", name),
            steps: vec![AgentStep {
                name: "work".to_string(),
                guard_in: Guard::None,
                // Use Custom action so delegation tests don't require an LLM client.
                action: StepAction::Custom(std::sync::Arc::new(|_ctx| {
                    Ok(StepOutput {
                        raw: "delegated work complete".to_string(),
                        parsed: None,
                        eval_result: None,
                    })
                })),
                guard_out: Guard::None,
                verdict: Verdict::Automated(Guard::None),
                tools: ToolSet::None,
                injection_protection: InjectionProtection::None,
                output_schema: None,
                dependencies: Vec::new(),
                parallel: false,
                input_processors: vec![],
                output_processors: vec![],
            }],
            on_failure: FailureMode::Abort,
            max_retries: 0,
        },
        tools: ToolSet::None,
        skills: SkillSet::default(),
        policy: AgentPolicy::default(),
        scorers: vec![],
    }
}

fn orchestrator_pipeline(child_agent: &str) -> Pipeline {
    Pipeline {
        name: "orchestrator".to_string(),
        steps: vec![AgentStep {
            name: "delegate".to_string(),
            guard_in: Guard::None,
            action: StepAction::DelegateAgent {
                agent: child_agent.to_string(),
                input: json!({ "task": "do something" }),
                expected_output_schema: None,
                delegation_policy: DelegationPolicy {
                    max_depth: 3,
                    allowed_agents: vec![child_agent.to_string()],
                    require_output_schema: false,
                    inherit_tool_scope: true,
                    inherit_budget: true,
                    require_user_approval: false,
                    memory_isolation: MemoryIsolation::Isolated,
                    on_delegation_start: None,
                    on_delegation_complete: None,
                    on_iteration_complete: None,
                    message_filter: None,
                },
                detached: false,
            },
            guard_out: Guard::None,
            verdict: Verdict::Automated(Guard::None),
            tools: ToolSet::None,
            injection_protection: InjectionProtection::None,
            output_schema: None,
            dependencies: Vec::new(),
            parallel: false,
            input_processors: vec![],
            output_processors: vec![],
        }],
        on_failure: FailureMode::Abort,
        max_retries: 0,
    }
}

fn orchestrator_agent(child_agent: &str) -> Agent {
    Agent {
        name: "orchestrator".to_string(),
        description: "Orchestrator agent".to_string(),
        pipeline: orchestrator_pipeline(child_agent),
        tools: ToolSet::None,
        skills: SkillSet::default(),
        policy: AgentPolicy::default(),
        scorers: vec![],
    }
}

